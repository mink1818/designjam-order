create table if not exists public.customer_item_prices (
  id bigint generated by default as identity primary key,
  customer_id uuid not null references public.customers(id) on delete cascade,
  item_number text not null,
  price integer not null check (price > 0 and price % 50 = 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(customer_id,item_number)
);

alter table public.customer_item_prices enable row level security;
delete from public.customer_item_prices where price<=0;
with ranked as (
  select id,row_number() over(
    partition by customer_id,regexp_replace(upper(trim(item_number)),'^[SBI][-_[:space:]]+','')
    order by updated_at desc nulls last,id desc
  ) rn from public.customer_item_prices
)
delete from public.customer_item_prices p using ranked r where p.id=r.id and r.rn>1;
update public.customer_item_prices
set item_number=regexp_replace(upper(trim(item_number)),'^[SBI][-_[:space:]]+',''),updated_at=now()
where item_number<>regexp_replace(upper(trim(item_number)),'^[SBI][-_[:space:]]+','');
drop policy if exists customer_item_prices_select on public.customer_item_prices;
create policy customer_item_prices_select on public.customer_item_prices
for select to authenticated
using (customer_id=auth.uid() or public.is_inventory_admin());
drop policy if exists customer_item_prices_admin_write on public.customer_item_prices;
create policy customer_item_prices_admin_write on public.customer_item_prices
for all to authenticated
using (public.is_inventory_admin()) with check (public.is_inventory_admin());

create or replace function public.upsert_customer_item_prices(p_prices jsonb)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_row jsonb;
  v_customer uuid;
  v_item text;
  v_price integer;
  v_saved integer:=0;
  v_updated_orders integer:=0;
  v_changed integer;
begin
  if not public.is_inventory_admin() then raise exception '관리자 권한이 필요합니다.'; end if;
  if p_prices is null or jsonb_typeof(p_prices)<>'array' then raise exception '단가 자료 형식이 올바르지 않습니다.'; end if;
  for v_row in select * from jsonb_array_elements(p_prices)
  loop
    begin v_customer:=(v_row->>'customer_id')::uuid; exception when others then continue; end;
    v_item:=regexp_replace(upper(trim(coalesce(v_row->>'item_number',''))),'^[SBI][-_[:space:]]+','');
    begin v_price:=(v_row->>'price')::integer; exception when others then continue; end;
    if v_customer is null or v_item='' or v_price<=0 or mod(v_price,50)<>0 then continue; end if;
    if not exists(select 1 from public.customers where id=v_customer and coalesce(is_admin,false)=false) then continue; end if;
    insert into public.customer_item_prices(customer_id,item_number,price,updated_at)
    values(v_customer,v_item,v_price,now())
    on conflict(customer_id,item_number) do update set price=excluded.price,updated_at=now();
    v_saved:=v_saved+1;
    update public.orders
       set price=v_price,total=greatest(0,coalesce(qty,0))*v_price
     where customer_id=v_customer
       and status<>'출고완료'
       and regexp_replace(upper(trim(item_number)),'^[SBI][-_[:space:]]+','')=v_item
       and (price is distinct from v_price or total is distinct from greatest(0,coalesce(qty,0))*v_price);
    get diagnostics v_changed=row_count;
    v_updated_orders:=v_updated_orders+v_changed;
  end loop;
  return jsonb_build_object('ok',true,'saved',v_saved,'updated_open_orders',v_updated_orders);
end;
$$;

create or replace function public.get_my_customer_item_prices()
returns table(item_number text,price integer)
language sql
stable
security definer
set search_path=public
as $$
  select p.item_number,p.price from public.customer_item_prices p
  where p.customer_id=auth.uid() and p.price>0 order by p.item_number;
$$;

create or replace function public.get_admin_customer_item_prices()
returns table(customer_id uuid,item_number text,price integer)
language plpgsql
stable
security definer
set search_path=public
as $$
begin
  if not public.is_inventory_admin() then raise exception '관리자 권한이 필요합니다.'; end if;
  return query select p.customer_id,p.item_number,p.price from public.customer_item_prices p where p.price>0 order by p.customer_id,p.item_number;
end;
$$;

create or replace function public.apply_customer_item_price_to_order()
returns trigger language plpgsql security definer set search_path=public as $$
declare v_price integer;
begin
  if new.customer_id is null then return new; end if;
  select p.price into v_price from public.customer_item_prices p
   where p.customer_id=new.customer_id
     and regexp_replace(upper(trim(p.item_number)),'^[SBI][-_[:space:]]+','')=
         regexp_replace(upper(trim(new.item_number)),'^[SBI][-_[:space:]]+','')
   order by p.updated_at desc nulls last,p.id desc limit 1;
  if found then new.price:=v_price;new.total:=greatest(0,coalesce(new.qty,0))*v_price;end if;
  return new;
end;$$;

drop trigger if exists orders_apply_customer_item_price on public.orders;
create trigger orders_apply_customer_item_price before insert on public.orders
for each row execute function public.apply_customer_item_price_to_order();

revoke all on function public.upsert_customer_item_prices(jsonb) from public;
revoke all on function public.get_my_customer_item_prices() from public;
revoke all on function public.get_admin_customer_item_prices() from public;
grant execute on function public.upsert_customer_item_prices(jsonb) to authenticated;
grant execute on function public.get_my_customer_item_prices() to authenticated;
grant execute on function public.get_admin_customer_item_prices() to authenticated;
